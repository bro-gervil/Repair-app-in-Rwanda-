const LanguageContext = createContext<LanguageContextType>({
  language: 'rw',
  setLanguage: () => {},
  t: (key: string, fallback?: string) => fallback || key,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem('giratech_lang') as Language;
      if (saved && ['rw', 'en', 'fr'].includes(saved)) {
        return saved;
      }
    } catch (e) {}
    return 'rw'; // Default to Kinyarwanda as primary local Rwandan language
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('giratech_lang', lang);
    } catch (e) {}
  };

  const t = (key: string, fallback?: string): string => {
    const langDict = translations[language];
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    // Fallback 1: English
    const enDict = translations.en;
    if (enDict && enDict[key]) {
      return enDict[key];
    }
    // Fallback 2: French
    const frDict = translations.fr;
    if (frDict && frDict[key]) {
      return frDict[key];
    }
    // Fallback 3: Kinyarwanda
    const rwDict = translations.rw;
    if (rwDict && rwDict[key]) {
      return rwDict[key];
    }
    return fallback || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
